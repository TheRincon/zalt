//! Emitting a recipe manifest.
//!
//! The counterpart to `zalt_recipe::parse`, and deliberately *here* rather than
//! in `zalt-recipe`: writing a manifest is a dev-time act, and the crate a
//! browser links should not carry a serialiser it will never call.
//!
//! The property that matters is that the two agree, which
//! `emitted_manifests_parse_back_to_what_they_describe` checks by round trip.
//! An emitter whose output the parser rejects is a tool that produces files
//! nothing can read; one whose output parses to a *different* recipe is worse,
//! because it produces files that load and are wrong.

use std::fmt::Write as _;

use zalt_recipe::recipe::{DictionarySource, Recipe, Strategy};

fn strategy_name(s: Strategy) -> &'static str {
    match s {
        Strategy::Compress => "compress",
        Strategy::Stored => "stored",
    }
}

fn quote(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

fn list(values: &[String]) -> String {
    let quoted: Vec<String> = values.iter().map(|v| quote(v)).collect();
    format!("[{}]", quoted.join(", "))
}

/// Render a recipe as a manifest this workspace's parser accepts.
///
/// Emits a *starter* file. The hand-written manifests carry prose explaining
/// why each number is what it is, and nothing here can reproduce that — which
/// is why `build` writes one only when asked, and never over an existing file.
pub fn emit(recipe: &Recipe) -> String {
    let mut s = String::new();

    let _ = writeln!(s, "# Generated by zalt-recipe-train.");
    let _ = writeln!(s, "#");
    let _ = writeln!(
        s,
        "# A starting point, not a finished manifest: the numbers below were"
    );
    let _ = writeln!(
        s,
        "# measured, but the reasons they are worth keeping have to be written"
    );
    let _ = writeln!(s, "# by whoever understands the content class.");
    let _ = writeln!(s);

    let _ = writeln!(s, "[recipe]");
    let _ = writeln!(s, "name = {}", quote(&recipe.name));

    if !recipe.match_.is_empty() {
        let _ = writeln!(s, "\n[match]");
        if !recipe.match_.content_types.is_empty() {
            let _ = writeln!(s, "content_type = {}", list(&recipe.match_.content_types));
        }
        if !recipe.match_.extensions.is_empty() {
            let _ = writeln!(s, "extension = {}", list(&recipe.match_.extensions));
        }
    }

    if let Some(d) = &recipe.dictionary {
        let _ = writeln!(s, "\n[dictionary]");
        if let DictionarySource::Path(p) = &d.source {
            let _ = writeln!(s, "path = {}", quote(p));
        }
        match d.id {
            Some(id) => {
                let _ = writeln!(s, "id = 0x{id:08X}");
            }
            None => {
                // Said out loud, because an absent `id` looks like an omission
                // and is a statement: a raw content prefix has no identity to
                // declare, and `dcz` supplies one out of band instead.
                let _ = writeln!(
                    s,
                    "# no id: a raw content-prefix dictionary carries none (RFC 9842 §5)"
                );
            }
        }
    }

    let e = &recipe.encode;
    if e.level.is_some() || e.window_log.is_some() || e.strategy != Strategy::Compress {
        let _ = writeln!(s, "\n[encode]");
        if let Some(level) = e.level {
            let _ = writeln!(s, "level = {level}");
        }
        if let Some(window_log) = e.window_log {
            let _ = writeln!(s, "window_log = {window_log}");
        }
        if e.strategy != Strategy::Compress {
            let _ = writeln!(s, "strategy = {}", quote(strategy_name(e.strategy)));
        }
    }

    let d = &recipe.decode;
    if d.max_window_log.is_some() || d.max_decoded_size.is_some() || d.total_memory.is_some() {
        let _ = writeln!(s, "\n[decode]");
        if let Some(log) = d.max_window_log {
            let _ = writeln!(s, "max_window_log = {log}");
        }
        if let Some(n) = d.max_decoded_size {
            let _ = writeln!(s, "max_decoded = {n}");
        }
        if let Some(n) = d.total_memory {
            let _ = writeln!(s, "total_memory = {n}");
        }
    }

    for rule in &recipe.rules {
        let _ = writeln!(s, "\n[[rule]]");
        if !rule.match_.content_types.is_empty() {
            let _ = writeln!(
                s,
                "match_content_type = {}",
                list(&rule.match_.content_types)
            );
        }
        if !rule.match_.extensions.is_empty() {
            let _ = writeln!(s, "match_extension = {}", list(&rule.match_.extensions));
        }
        if let Some(strategy) = rule.strategy {
            let _ = writeln!(s, "strategy = {}", quote(strategy_name(strategy)));
        }
        if let Some(level) = rule.level {
            let _ = writeln!(s, "level = {level}");
        }
    }

    s
}
